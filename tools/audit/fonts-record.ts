/**
 * Keeps the "What each theme uses today" table of `docs/templates/modals/FONT_RECORD.md` in step with
 * the `fonts` token of every theme (`src/ui/theme/modal-styles.ts`). The table sits between two
 * markers and is written by this script, so it cannot drift from the code. The rest of the record
 * is written by hand; `tests/tools/fonts-record.test.ts` checks that both parts stay true.
 *
 * Usage: `npm run docs:fonts` (write), `npm run docs:fonts -- --check` (fail when stale).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { MODAL_STYLES, type ModalStyle } from '../../src/ui/theme/modal-styles';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const FONT_RECORD_FILE = 'docs/templates/modals/FONT_RECORD.md';

export const START_MARKER =
  '<!-- fonts-record:start (generated by `npm run docs:fonts`, do not edit) -->';
export const END_MARKER = '<!-- fonts-record:end -->';

const SYSTEM_NAMES: Record<string, string> = {
  'ui-serif': 'system serif',
  'ui-monospace': 'system monospace',
  'system-ui': 'system sans',
};

/** The first family of a CSS font-family value, as a name a person would say. */
export const familyName = (stack: string): string => {
  const first = stack
    .split(',')[0]
    .trim()
    .replace(/^['"]|['"]$/g, '');
  return SYSTEM_NAMES[first] ?? first;
};

const bold = (text: string): string => `**${text}**`;

const signed = (size: number): string => (size > 0 ? `+${size}` : String(size));

/** The theme's text size changes in px, e.g. "Body +2, Numbers +1, Newspaper headlines -1". */
const sizesCell = (fonts: ModalStyle['fonts']): string => {
  const { sizes } = fonts;
  const parts: [string, number | undefined][] = [
    ['Headlines', sizes?.headline],
    ['Body', sizes?.body],
    ['Numbers', sizes?.numbers],
    ['Newspaper headlines', sizes?.newspaper?.headline],
    ['Newspaper body', sizes?.newspaper?.body],
  ];
  const set = parts.filter(([, size]) => size !== undefined && size !== 0);
  return set.length === 0
    ? 'none'
    : set.map(([name, size]) => `${name} ${signed(size as number)}`).join(', ');
};

interface Row {
  theme: string;
  cells: string[];
}

const row = (style: ModalStyle): Row => {
  const { fonts } = style;
  const headline = familyName(fonts.headline);
  const body = familyName(fonts.body);
  const news = fonts.newspaper;
  return {
    theme: style.label,
    cells: [
      headline,
      body,
      news?.headline ? bold(`${familyName(news.headline)} (set)`) : `follows (${headline})`,
      news?.body ? bold(`${familyName(news.body)} (set)`) : `follows (${body})`,
      fonts.numbers ? familyName(fonts.numbers) : 'system monospace',
      sizesCell(fonts),
    ],
  };
};

/** The generated block: the table, and one sentence on which themes set a Newspaper font. */
export const buildThemeFontsBlock = (styles: readonly ModalStyle[] = MODAL_STYLES): string => {
  const header = [
    'Theme',
    'Headlines',
    'Body',
    'Newspaper headlines',
    'Newspaper body',
    'Numbers & codes',
    'Text size change (px)',
  ];
  const rows = styles.map(row);
  const lines = [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${[r.theme, ...r.cells].join(' | ')} |`),
  ];
  const withNewspaper = styles.filter((s) => s.fonts.newspaper).map((s) => s.label);
  const sentence =
    withNewspaper.length === 0
      ? 'No theme sets a Newspaper font: every newspaper follows its theme.'
      : `Themes that set a Newspaper font: ${withNewspaper.join(', ')}. Every other newspaper follows its theme.`;
  return `${lines.join('\n')}\n\n${sentence}`;
};

/** The record with the generated block rewritten between the markers. Throws when a marker is missing. */
export const renderFontRecord = (
  source: string,
  styles: readonly ModalStyle[] = MODAL_STYLES,
): string => {
  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  const text = source.replace(/\r\n/g, '\n');
  const start = text.indexOf(START_MARKER);
  const end = text.indexOf(END_MARKER);
  if (start < 0 || end < 0 || end < start) {
    throw new Error(`${FONT_RECORD_FILE} must contain the fonts-record start and end markers.`);
  }
  const rendered =
    text.slice(0, start + START_MARKER.length) +
    '\n' +
    buildThemeFontsBlock(styles) +
    '\n' +
    text.slice(end);
  return eol === '\r\n' ? rendered.replace(/\n/g, '\r\n') : rendered;
};

function main(): void {
  const file = path.join(REPO_ROOT, FONT_RECORD_FILE);
  const current = fs.readFileSync(file, 'utf8');
  const next = renderFontRecord(current);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error(`${FONT_RECORD_FILE} is stale. Run \`npm run docs:fonts\`.`);
      process.exitCode = 1;
    } else {
      console.log(`${FONT_RECORD_FILE} is up to date.`);
    }
    return;
  }
  if (next === current) {
    console.log(`${FONT_RECORD_FILE} is up to date.`);
    return;
  }
  fs.writeFileSync(file, next, 'utf8');
  console.log(`${FONT_RECORD_FILE} updated.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

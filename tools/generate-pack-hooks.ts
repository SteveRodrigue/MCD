/**
 * Marvel Champions Digital (MCD) - Pack hook map generator.
 *
 * Official packs keep their code in `content/packs/<id>/scripts/index.ts` (ADR-0092). This scans
 * the content folder and writes `src/data/content/pack-hooks.generated.ts`, a static import map
 * keyed by pack id, so adding a pack with hooks needs no hand-edited registry in the engine.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { listPackCodes, packDir } from '../src/tools/content-paths';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const HOOKS_OUTPUT = 'src/data/content/pack-hooks.generated.ts';

/** Ids of the packs that have a `scripts/index.ts`, sorted. */
export function packsWithHooks(base: string = REPO_ROOT): string[] {
  return listPackCodes(base).filter((code) =>
    fs.existsSync(path.join(packDir(code, base), 'scripts', 'index.ts')),
  );
}

export function generatePackHooksSource(base: string = REPO_ROOT): string {
  const ids = packsWithHooks(base);
  const identifier = (id: string) => `hooks_${id}`;
  const imports = ids.map(
    (id) => `import ${identifier(id)} from '../../../content/packs/${id}/scripts/index';`,
  );
  const entries = ids.map((id) => `  ${id}: ${identifier(id)},`);
  return [
    '// Generated by tools/generate-pack-hooks.ts (npm run schema:generate). Do not edit.',
    "import type { PackHooks } from '@engine/plugin-api';",
    ...imports,
    '',
    '/** Code hooks of the official packs that have a scripts folder, keyed by pack id. */',
    `export const packHooks: Record<string, PackHooks> = {${entries.length ? '\n' + entries.join('\n') + '\n' : ''}};`,
    '',
  ].join('\n');
}

export function writePackHooks(base: string = REPO_ROOT): string {
  const output = path.resolve(base, HOOKS_OUTPUT);
  fs.writeFileSync(output, generatePackHooksSource(base), 'utf-8');
  console.log(`✅ Pack hook map written to ${output}`);
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writePackHooks();
}
